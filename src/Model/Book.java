package Model;

public abstract class Book {
    // Encapsulation: Fields ko private rakha hai
    private String bookId;
    private String title;
    private String author;

    public Book(String bookId, String title, String author) {
        this.bookId = bookId;
        this.title = title;
        this.author = author;
    }

    // Getters and Setters (Controlled Access)
    public String getBookId() {
        return bookId;
    }

    public void setBookId(String bookId) {
        this.bookId = bookId;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getAuthor() {
        return author;
    }

    public void setAuthor(String author) {
        this.author = author;
    }

    // Polymorphism ke liye Abstract Method (Har subclass isse apne tareeke se define karegi)
    public abstract double getRentalPrice(int days);
}